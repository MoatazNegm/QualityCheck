import React, { useState } from 'react';
import { useAuth } from '../context/AuthContext';

const LoginScreen: React.FC = () => {
  const { login, loginWithKey } = useAuth();
  const [loginMode, setLoginMode] = useState<'password' | 'key'>('password');
  const [username, setUsername] = useState('');
  const [password, setPassword] = useState('');
  const [apiKey, setApiKey] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const handleSubmit = async (e: any) => {
    e.preventDefault();
    setLoading(true);
    setError('');

    try {
      if (loginMode === 'key') {
        if (!apiKey.trim()) {
          throw new Error('Please enter your generated key');
        }
        await loginWithKey(apiKey.trim());
      } else {
        await login(username, password);
      }
    } catch (err: any) {
      setError(err?.message || 'Login failed. Please check your credentials.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className='login-container'>
      <img src='/quickstor-logo.png' alt='Quickstor Logo' className='login-logo' />
      <h2>QualityCheck Login</h2>

      {/* Mode Switcher */}
      <div style={{
        display: 'flex',
        gap: '0.4rem',
        marginBottom: '1.25rem',
        background: 'rgba(255, 255, 255, 0.05)',
        padding: '3px',
        borderRadius: '8px',
        border: '1px solid rgba(255, 255, 255, 0.1)'
      }}>
        <button
          type='button'
          onClick={() => { setLoginMode('password'); setError(''); }}
          style={{
            flex: 1,
            padding: '0.5rem 0.75rem',
            borderRadius: '6px',
            border: 'none',
            background: loginMode === 'password' ? 'var(--accent-color, #4f46e5)' : 'transparent',
            color: loginMode === 'password' ? '#fff' : 'var(--text-muted, #a0aec0)',
            cursor: 'pointer',
            fontSize: '0.85rem',
            fontWeight: 600,
            transition: 'all 0.2s ease'
          }}
        >
          Password
        </button>
        <button
          type='button'
          onClick={() => { setLoginMode('key'); setError(''); }}
          style={{
            flex: 1,
            padding: '0.5rem 0.75rem',
            borderRadius: '6px',
            border: 'none',
            background: loginMode === 'key' ? 'var(--accent-color, #4f46e5)' : 'transparent',
            color: loginMode === 'key' ? '#fff' : 'var(--text-muted, #a0aec0)',
            cursor: 'pointer',
            fontSize: '0.85rem',
            fontWeight: 600,
            transition: 'all 0.2s ease'
          }}
        >
          🔑 Generated Key
        </button>
      </div>

      <form onSubmit={handleSubmit}>
        {error && (
          <div style={{
            background: 'rgba(239, 68, 68, 0.15)',
            border: '1px solid #ef4444',
            color: '#fca5a5',
            padding: '0.6rem 0.8rem',
            borderRadius: '6px',
            marginBottom: '1rem',
            fontSize: '0.9rem'
          }}>
            ⚠️ {error}
          </div>
        )}

        {loginMode === 'password' ? (
          <>
            <div>
              <label>Username:</label>
              <input
                type='text'
                value={username}
                onChange={e => { setUsername(e.target.value); setError(''); }}
                autoFocus
                required
              />
            </div>
            <div>
              <label>Password:</label>
              <input
                type='password'
                value={password}
                onChange={e => { setPassword(e.target.value); setError(''); }}
                required
              />
            </div>
          </>
        ) : (
          <div>
            <label>Generated Key:</label>
            <input
              type='text'
              value={apiKey}
              onChange={e => { setApiKey(e.target.value); setError(''); }}
              placeholder='qc_...'
              autoFocus
              required
              style={{ fontFamily: 'monospace' }}
            />
            <small style={{ color: 'var(--text-muted, #a0aec0)', fontSize: '0.78rem', display: 'block', marginTop: '0.35rem' }}>
              Enter or paste the key generated by your administrator to logon.
            </small>
          </div>
        )}

        <button type='submit' disabled={loading} style={{ marginTop: '0.5rem' }}>
          {loading ? 'Logging in...' : loginMode === 'key' ? '🔑 Log In with Key' : 'Login'}
        </button>
      </form>
    </div>
  );
};

export default LoginScreen;